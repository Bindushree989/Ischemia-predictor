$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Push-Location $repoRoot

function New-RandomHex {
    $bytes = New-Object byte[] 32
    $generator = [Security.Cryptography.RandomNumberGenerator]::Create()
    try {
        $generator.GetBytes($bytes)
    }
    finally {
        $generator.Dispose()
    }
    return [BitConverter]::ToString($bytes).Replace("-", "").ToLowerInvariant()
}

function Invoke-CreateClinician($docker) {
    $username = Read-Host "Initial clinician username (existing accounts are left unchanged)"
    if ($username -notmatch "^[A-Za-z0-9._-]{1,64}$") {
        throw "Username must be 1-64 characters and contain only letters, numbers, '.', '_' or '-'."
    }

    $securePassword = Read-Host "Clinician password (10+ characters with upper, lower, digit and symbol)" -AsSecureString
    $passwordPointer = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($securePassword)
    try {
        $password = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($passwordPointer)
    }
    finally {
        [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($passwordPointer)
    }

    $startInfo = New-Object System.Diagnostics.ProcessStartInfo
    $startInfo.FileName = $docker
    $startInfo.Arguments = "compose exec -T web python -m scripts.create_user $username Clinician --password-stdin --if-not-exists"
    $startInfo.WorkingDirectory = $repoRoot
    $startInfo.UseShellExecute = $false
    $startInfo.CreateNoWindow = $true
    $startInfo.RedirectStandardInput = $true
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $startInfo
    [void]$process.Start()
    $stdoutTask = $process.StandardOutput.ReadToEndAsync()
    $stderrTask = $process.StandardError.ReadToEndAsync()
    $process.StandardInput.WriteLine($password)
    $process.StandardInput.Close()
    $process.WaitForExit()
    $stdout = $stdoutTask.Result
    $stderr = $stderrTask.Result
    $password = $null

    if ($stdout) {
        Write-Host $stdout.Trim()
    }
    if ($stderr) {
        Write-Host $stderr.Trim()
    }
    if ($process.ExitCode -ne 0) {
        throw "Could not create the clinician account. Check the password policy and application logs."
    }
}

try {
    $dockerCommand = Get-Command docker -ErrorAction SilentlyContinue
    if ($dockerCommand) {
        $docker = $dockerCommand.Source
    }
    else {
        $dockerBin = Join-Path $env:ProgramFiles "Docker\Docker\resources\bin"
        $docker = Join-Path $dockerBin "docker.exe"
        if (-not (Test-Path $docker)) {
            throw "Docker CLI not found. Install Docker Desktop and reopen PowerShell."
        }
        $env:PATH = "$dockerBin;$env:PATH"
    }

    & $docker info --format "{{.ServerVersion}}" *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker engine is not available. Start Docker Desktop and try again."
    }

    & $docker compose version *> $null
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose v2 is unavailable. Update Docker Desktop."
    }

    $envPath = Join-Path $repoRoot ".env"
    if (-not (Test-Path $envPath)) {
        @(
            "# Generated by scripts/start.ps1. Keep this file private."
            "POSTGRES_PASSWORD=$(New-RandomHex)"
            "SECRET_KEY=$(New-RandomHex)"
            "DATA_KEY=$(New-RandomHex)"
        ) | Set-Content -Path $envPath -Encoding ASCII
        Write-Host "Created .env with fresh secrets."
    }
    else {
        $envContent = Get-Content $envPath -Raw
        foreach ($key in @("POSTGRES_PASSWORD", "SECRET_KEY", "DATA_KEY")) {
            if ($envContent -notmatch "(?m)^$key=.+$") {
                throw ".env is missing $key. Add it using .env.example as a guide."
            }
        }
        if ($envContent -notmatch "(?m)^DATA_KEY=[0-9a-fA-F]{64}\s*$") {
            throw ".env DATA_KEY must be exactly 64 hexadecimal characters."
        }
    }

    Write-Host "Starting the persistent MLflow tracking server..."
    & $docker compose up --build --detach mlflow
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose failed to start MLflow."
    }

    $mlflowReady = $false
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        $containerId = & $docker compose ps -q mlflow
        $health = if ($containerId) {
            & $docker inspect --format "{{.State.Health.Status}}" $containerId 2>$null
        }
        if ($health -eq "healthy") {
            $mlflowReady = $true
            break
        }
        Start-Sleep -Seconds 2
    }
    if (-not $mlflowReady) {
        & $docker compose logs --tail 80 mlflow
        throw "MLflow tracking server did not become healthy."
    }

    Write-Host "Reproducing the DVC training pipeline and logging runs to MLflow..."
    & $docker compose run --rm trainer
    if ($LASTEXITCODE -ne 0) {
        throw "DVC training pipeline failed. Check the output above and MLflow logs."
    }

    $registryPath = Join-Path $repoRoot "models\registry.json"
    $pipelinePath = Join-Path $repoRoot "models\pipeline-1.0.joblib"
    if (-not (Test-Path $registryPath) -or -not (Test-Path $pipelinePath)) {
        throw "DVC completed without generating the model registry and preprocessing artifact."
    }
    $registry = Get-Content $registryPath -Raw | ConvertFrom-Json
    foreach ($modelType in @("ML", "DL", "QML")) {
        $entry = $registry | Where-Object { $_.type -eq $modelType } | Select-Object -First 1
        if (-not $entry -or -not (Test-Path (Join-Path (Join-Path $repoRoot "models") $entry.file))) {
            throw "DVC completed but the $modelType model or its registry entry is missing."
        }
    }

    Write-Host "Starting PostgreSQL, web gateway, and ML/DL/QML prediction services..."
    & $docker compose up --build --detach
    if ($LASTEXITCODE -ne 0) {
        throw "Docker Compose failed to build or start the application."
    }

    $ready = $false
    for ($attempt = 0; $attempt -lt 60; $attempt++) {
        try {
            $response = Invoke-WebRequest -Uri "http://localhost:5000/" -UseBasicParsing -TimeoutSec 3
            if ($response.StatusCode -eq 200) {
                $ready = $true
                break
            }
        }
        catch {
            Start-Sleep -Seconds 2
        }
    }

    if (-not $ready) {
        & $docker compose ps
        & $docker compose logs --tail 80
        throw "Application did not become ready at http://localhost:5000."
    }

    Invoke-CreateClinician $docker
    & $docker compose ps
    Write-Host "Application is ready: http://localhost:5000"
    Write-Host "MLflow tracking UI: http://localhost:5001"
}
finally {
    Pop-Location
}
